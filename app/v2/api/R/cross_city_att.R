#' ULEZ-era weekends at CCZ monitors — THE ONE SWITCH (ADR-0043 addendum).
#'
#' From 2019-04-08 (central ULEZ, 7/7) to 2020-06-21 the CCZ itself still
#' charged Mon–Fri only; from 2020-06-22 the CCZ charges weekends too
#' (charge_calendar.csv, LON-CCZ rows). So in that window a CCZ monitor's
#' weekend is charged by the ULEZ and NOT by the CCZ.
#'
#'   "either_or" (DEFAULT, the ruling): a day is charged if ANY covering scheme
#'       charges (Tim 2026-08-09, REAFFIRMED 2026-09-30: "Keep them charged:
#'       either/or rule."). Those weekends stay in every CCZ pool.
#'   "ccz_only": the CCZ's own schedule — those weekends leave the CCZ pool.
#'       On pin 5826 that is 436 monitor-days and moves the whole-history
#'       cordon ATT by about -0.008 (LONDON_REVIEW_2026-09-30 §3).
#'
#' Resolution order: the explicit argument, else env
#' `CPPORTAL_LONDON_ULEZ_ERA_WEEKENDS`, else "either_or". It is the ONLY place
#' the choice is made; `cpportal_select_cells()` (paper + portal) reads it.
#' Wired, NOT flipped.
CPPORTAL_LONDON_CCZ_WEEKDAYS_ONLY_FROM <- as.Date("2019-04-08")
CPPORTAL_LONDON_CCZ_WEEKDAYS_ONLY_TO   <- as.Date("2020-06-21")
cpportal_ulez_era_weekends_mode <- function(mode = NULL) {
  m <- mode %||% Sys.getenv("CPPORTAL_LONDON_ULEZ_ERA_WEEKENDS", "")
  m <- tolower(trimws(as.character(m)[1]))
  if (is.na(m) || !nzchar(m)) m <- "either_or"
  if (!m %in% c("either_or", "ccz_only"))
    stop("ulez_era_weekends must be 'either_or' or 'ccz_only', got '", m, "'",
         call. = FALSE)
  m
}

#' Drop the ULEZ-only weekend cells from a CCZ-set London cell tibble when the
#' mode is "ccz_only". Exact no-op under "either_or", for any other metro, and
#' for a monitor set that is not (a subset of) the CCZ set.
.cpportal_apply_ulez_era_weekends <- function(rows, metro_id, monitor_set,
                                              mode = "either_or") {
  if (!identical(mode, "ccz_only") || is.null(rows) || !nrow(rows)) return(rows)
  if (!identical(as.integer(metro_id), 943L) || is.null(monitor_set)) return(rows)
  if (!all(monitor_set %in% cpportal_london_monitor_set("ccz"))) return(rows)
  d <- as.Date(rows$day)
  wd <- as.integer(format(d, "%u"))          # 6 = Sat, 7 = Sun
  drop <- !is.na(d) & wd >= 6L &
    d >= CPPORTAL_LONDON_CCZ_WEEKDAYS_ONLY_FROM &
    d <= CPPORTAL_LONDON_CCZ_WEEKDAYS_ONLY_TO
  rows[!drop, , drop = FALSE]
}

#' THE shared cell selector: fitted-basis cells for ONE metro out of a pin's
#' `$att`, with the universal cuts applied. `.t1_cells()` (paper) and every
#' API pool call this, so the paper and the portal see an identical cell set.
#'
#' `unit = TRUE` reads `per_day_metro_unit` (monitor-day); FALSE reads
#' `per_day_metro` (metro-day, the J = 1 grain). `monitor_set` restricts unit
#' rows to those monitor ids. Dates are inclusive calendar bounds.
cpportal_select_cells <- function(att, metro_id, day_start = NULL, day_end = NULL,
                                  monitor_set = NULL, unit = TRUE,
                                  include_inactive = FALSE,
                                  ulez_era_weekends = NULL) {
  if (is.null(att) || !is.data.frame(att) || !nrow(att)) return(NULL)
  want <- if (isTRUE(unit) || !is.null(monitor_set)) "per_day_metro_unit" else "per_day_metro"
  rows <- att[as.character(att$type) == want, , drop = FALSE]
  if (!nrow(rows)) return(NULL)
  rows$metro_id <- suppressWarnings(as.integer(as.character(rows$metro_id)))
  rows$day <- as.Date(rows$day)
  rows <- rows[!is.na(rows$metro_id) & rows$metro_id == as.integer(metro_id), , drop = FALSE]
  if (!nrow(rows)) return(NULL)
  if (!is.null(monitor_set)) {
    idc <- .cpportal_unit_id_col(rows)
    if (is.na(idc)) idc <- "fullaqsid"
    rows <- rows[as.character(rows[[idc]]) %in% monitor_set, , drop = FALSE]
    if (!nrow(rows)) return(NULL)
  }
  if (!is.null(day_start)) rows <- rows[rows$day >= as.Date(day_start), , drop = FALSE]
  if (!is.null(day_end))   rows <- rows[rows$day <= as.Date(day_end), , drop = FALSE]
  if (!nrow(rows)) return(NULL)
  rows <- cpportal_charged_days_filter(rows, date_col = "day", metro_col = "metro_id",
                                       include_inactive = include_inactive)
  if (!nrow(rows)) return(NULL)
  # ULEZ-era weekends at CCZ monitors: the one switch (default either/or = kept).
  if (!isTRUE(include_inactive))
    rows <- .cpportal_apply_ulez_era_weekends(
      rows, metro_id, monitor_set, cpportal_ulez_era_weekends_mode(ulez_era_weekends))
  if (!nrow(rows)) return(NULL)
  rows <- cpportal_episode_days_filter(rows)
  if (!nrow(rows)) return(NULL)
  rows
}

#' Fitted cells for a SET of metros: monitor-day where the pin has them, the
#' metro-day row for a J = 1 city with no unit grain (the paper's fallback),
#' London restricted by `cpportal_london_monitor_set(london)`. One tibble with a
#' `cell_grain` column ("monitor_day" | "metro_day"); NULL when nothing lands.
#'
#' MEMOISED per process (perf pass 3, 2026-10-01; ADR-0043 addendum). Each
#' metro's selection is cached in `.cpportal_cells_memo`, keyed by the pin
#' identity the bundle loader stamps (`cpportal_att_id` attribute, written by
#' `cpportal_stamp_charged_days()`), the filtered table's row count and
#' `sum(att)` (so a pollutant / parameter subset of the same pin is a
#' different key), the metro, London's monitor set, the day window, the
#' inactive / ULEZ-weekend switches and every `CPPORTAL_*` env var. The cache
#' is dropped whenever the pin identity changes. A table without the stamp
#' (hand-built tibbles in tests, a loader that did not stamp) is never cached.
#' Kill switch: `CPPORTAL_FITTED_CELLS_MEMO=0`. Same rows either way.
cpportal_fitted_cells <- function(att, metro_ids, london = "ccz",
                                  day_start = NULL, day_end = NULL,
                                  include_inactive = FALSE,
                                  ulez_era_weekends = NULL) {
  mids <- unique(stats::na.omit(suppressWarnings(as.integer(metro_ids))))
  base_key <- .cpportal_cells_memo_key(att, london, day_start, day_end,
                                       include_inactive, ulez_era_weekends)
  out <- list()
  for (m in mids) {
    r <- if (is.null(base_key)) {
      .cpportal_fitted_cells_one(att, m, london, day_start, day_end,
                                 include_inactive, ulez_era_weekends)
    } else {
      k <- paste0(base_key, "|m=", m,
                  if (m == LONDON_CCZ_METRO_ID) paste0("|l=", paste(london, collapse = ",")) else "")
      hit <- .cpportal_cells_memo$entries[[k]]
      if (is.null(hit)) {
        v <- .cpportal_fitted_cells_one(att, m, london, day_start, day_end,
                                        include_inactive, ulez_era_weekends)
        .cpportal_cells_memo$entries[[k]] <- list(v = v)
        v
      } else hit$v
    }
    if (!is.null(r)) out[[length(out) + 1L]] <- r
  }
  if (!length(out)) return(NULL)
  dplyr::bind_rows(out)
}

.cpportal_cells_memo <- new.env(parent = emptyenv())
.cpportal_cells_memo$id <- NULL
.cpportal_cells_memo$entries <- list()

#' Memo key prefix for `cpportal_fitted_cells()`, or NULL = do not cache.
#' Resets the cache when the pin identity differs from the cached one.
.cpportal_cells_memo_key <- function(att, london, day_start, day_end,
                                     include_inactive, ulez_era_weekends) {
  if (identical(Sys.getenv("CPPORTAL_FITTED_CELLS_MEMO", "1"), "0")) return(NULL)
  if (!is.data.frame(att)) return(NULL)
  id <- attr(att, "cpportal_att_id", exact = TRUE)
  if (is.null(id) || !is.character(id) || length(id) != 1L) return(NULL)
  if (!is.double(att$att)) return(NULL)
  if (!identical(.cpportal_cells_memo$id, id)) {
    .cpportal_cells_memo$id <- id
    .cpportal_cells_memo$entries <- list()
  }
  ev <- Sys.getenv()
  ev <- ev[startsWith(names(ev), "CPPORTAL_")]
  ev <- ev[order(names(ev))]
  dk <- function(d) if (is.null(d)) "NULL" else paste(as.character(as.Date(d)), collapse = ",")
  paste0(id, "|n=", nrow(att),
         "|s=", sprintf("%.17g", sum(att$att, na.rm = TRUE)),
         "|d0=", dk(day_start), "|d1=", dk(day_end),
         "|ia=", isTRUE(include_inactive),
         "|uw=", if (is.null(ulez_era_weekends)) "NULL" else paste(ulez_era_weekends, collapse = ","),
         "|env=", paste(names(ev), ev, sep = "=", collapse = ";"))
}

#' One metro's fitted cells (the unmemoised body of `cpportal_fitted_cells()`).
.cpportal_fitted_cells_one <- function(att, m, london, day_start, day_end,
                                       include_inactive, ulez_era_weekends) {
  {
    mset <- if (m == LONDON_CCZ_METRO_ID) cpportal_london_monitor_set(london) else NULL
    r <- cpportal_select_cells(att, m, day_start, day_end, monitor_set = mset,
                               unit = TRUE, include_inactive = include_inactive,
                               ulez_era_weekends = ulez_era_weekends)
    g <- "monitor_day"
    if (is.null(r) && is.null(mset)) {
      r <- cpportal_select_cells(att, m, day_start, day_end, monitor_set = NULL,
                                 unit = FALSE, include_inactive = include_inactive)
      g <- "metro_day"
    }
    if (is.null(r) || !nrow(r)) return(NULL)
    keep <- intersect(c("metro_id", "day", "fullaqsid", "monitor_id", "att", "se_att",
                        "yhat0", "episode_flag", "basis"), names(r))
    r <- r[, keep, drop = FALSE]
    r$att <- suppressWarnings(as.numeric(as.character(r$att)))
    if ("se_att" %in% names(r)) r$se_att <- suppressWarnings(as.numeric(as.character(r$se_att)))
    if ("yhat0" %in% names(r)) r$yhat0 <- suppressWarnings(as.numeric(as.character(r$yhat0)))
    if ("basis" %in% names(r)) r$basis <- as.character(r$basis)
    r$cell_grain <- g
    r <- tibble::as_tibble(r)
    attr(r, "cpportal_att_id") <- NULL
    r
  }
}

