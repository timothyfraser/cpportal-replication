.cpportal_monitor_effects_cache <- new.env(parent = emptyenv())

#' Windowed ATT for EVERY modeled monitor in a metro, one row per monitor.
#'
#' Why this exists: the map's effect colour ramp reads `monitor.att` off the
#' `/monitors` roster, and that column was null for every site — `/monitors`
#' comes from `public.monitors`, which knows nothing about the model. The
#' Effects table's per-monitor numbers come from the pin's `per_monitor`
#' aggregate (`.cpportal_att_monitor_level_from_bundle()`,
#' app/v2/api/R/data_fetch.R:1346), which is an **all-days** pool and therefore
#' not publicly shareable on its own terms.
#'
#' So this computes the *shareable* estimand instead, by reusing the exact pool
#' the Selected-set card already serves: a monitor is a one-element monitor set,
#' so per-monitor effect = `cpportal_monitor_set_window_summary()` (this file,
#' ~line 514) with `n_selected = 1`. That routes through
#' `cpportal_charged_days_filter()` + `cpportal_episode_days_filter()` +
#' `combine_att_window_d2b()` — windowed charged-days, identical cuts to
#' `/monitor-set-att-series?include_summary=1` and to Table 2's family. Raw pin
#' rows are never returned.
#'
#' Coverage is deliberately partial. Only `per_day_metro_unit` cells exist, and
#' only for **fitted** metros; anchored metros (Oslo at zone scope) put the
#' anchor at the metro basis and have no per-monitor decomposition at all. Every
#' monitor without cells is simply absent from the result and stays `att = NA`
#' downstream — the map's "without an estimate" legend is the honest rendering.
#'
#' @param metro_id Metro id.
#' @param pollutant Pollutant code, passed to `cross_city_filter_bundle_att()`.
#' @param spec_id,outcome,scope Pin selectors; defaults match
#'   `/monitor-set-att-series`.
#' @return Tibble `monitor_id`, `att`, `se`, `ci_lo`, `ci_hi`, `n_days`,
#'   `basis`, `estimand` — one row per monitor that has cells after the cuts.
#'   Zero rows when the pin is missing or the metro is anchored.
cpportal_monitor_window_effects <- function(metro_id,
                                            pollutant = "PM2.5",
                                            spec_id = "all_priority",
                                            outcome = "aq_daily_mean",
                                            scope = "zone") {
  empty <- tibble::tibble(
    monitor_id = character(), att = numeric(), se = numeric(),
    ci_lo = numeric(), ci_hi = numeric(), n_days = integer(),
    basis = character(), estimand = character()
  )
  mid <- suppressWarnings(as.integer(metro_id))
  if (!is.finite(mid)) return(empty)

  key <- paste(mid, pollutant, spec_id, outcome, scope, sep = "|")
  if (exists(key, envir = .cpportal_monitor_effects_cache, inherits = FALSE)) {
    return(get(key, envir = .cpportal_monitor_effects_cache))
  }

  finish <- function(x) {
    assign(key, x, envir = .cpportal_monitor_effects_cache)
    x
  }

  bundle <- tryCatch(load_fect_bundle(spec_id, outcome = outcome, scope = scope),
                     error = function(e) NULL)
  # No bundle (a missing pin or a failed read): answer empty but do NOT
  # memoise it, so a later successful read is used (2026-11-11 incident).
  if (is.null(bundle)) return(empty)
  if (is.null(bundle$att) || !"type" %in% names(bundle$att)) {
    return(finish(empty))
  }
  a <- tryCatch(cross_city_filter_bundle_att(bundle$att, pollutant),
                error = function(e) NULL)
  if (!is.data.frame(a) || nrow(a) == 0L || !"metro_id" %in% names(a)) {
    return(finish(empty))
  }

  uc <- intersect(c("fullaqsid", "monitor_id", "unit_id"), names(a))[1]
  dc <- intersect(c("day", "date"), names(a))[1]
  sc <- intersect(c("sediff", "se_att", "sediff_native"), names(a))[1]
  if (is.na(uc) || is.na(dc) || is.na(sc)) return(finish(empty))

  # Same normalisation `/monitor-set-att-series`'s `extract_pdu()` performs
  # (app/v2/api/plumber.R, "Extract a bundle's per_day_metro_unit rows"):
  # `metro_id` + `day` so the charged-days cut bites, `episode_flag` so the
  # episode cut does, and canonical `fullaqsid` so `.cpportal_unit_id_col()`
  # counts monitors the way every other combiner counts them.
  cells <- a |>
    dplyr::filter(.data$type == "per_day_metro_unit",
                  suppressWarnings(as.integer(.data$metro_id)) == !!mid) |>
    dplyr::mutate(
      fullaqsid = as.character(.data[[uc]]),
      day       = as.Date(.data[[dc]]),
      att       = as.numeric(.data$att),
      se_att    = as.numeric(.data[[sc]])
    ) |>
    dplyr::filter(is.finite(.data$att), nzchar(.data$fullaqsid), !is.na(.data$day))
  keep_cols <- intersect(c("metro_id", "episode_flag"), names(cells))
  cells <- dplyr::select(cells, dplyr::all_of(c("fullaqsid", "day", "att",
                                                "se_att", keep_cols)))
  if (nrow(cells) == 0L) return(finish(empty))

  ids <- sort(unique(cells$fullaqsid))
  rows <- lapply(ids, function(id) {
    s <- cpportal_monitor_set_window_summary(
      cells[cells$fullaqsid == id, , drop = FALSE],
      basis = "fitted", n_selected = 1L
    )
    tibble::tibble(
      monitor_id = id,
      att        = as.numeric(s$att),
      se         = as.numeric(s$se),
      ci_lo      = as.numeric(s$ci_lo),
      ci_hi      = as.numeric(s$ci_hi),
      n_days     = as.integer(s$n_monitor_days),
      basis      = as.character(s$basis),
      estimand   = as.character(s$estimand)
    )
  })
  out <- dplyr::bind_rows(rows)
  # A monitor whose cells all fell to the estimand cuts has no shareable
  # estimate; drop it rather than publishing an NA that reads as a zero.
  out <- dplyr::filter(out, is.finite(.data$att), .data$n_days > 0L)
  finish(if (nrow(out) == 0L) empty else out)
}


#' Join per-monitor windowed effects onto a `/monitors` roster, zone pin first
#' and the whole-metro pin for the rest, and say where each one came from.
#'
#' Why: the map's dots read `att` off `/monitors?include_effects=1`, which used
#' to ask only the **zone** pin, so every monitor outside the priced zone stayed
#' grey even when the whole-metro pin models it (NYC: 6 coloured of 45
#' modelled). This mirrors `/monitor-set-att-series?scope=auto` (zone pin first,
#' metro pin fills the rest) at the one-monitor grain. No new arithmetic: each
#' scope is exactly `cpportal_monitor_window_effects()`, i.e. the Selected-set
#' pool with `n_selected = 1`.
#'
#' Per row it adds:
#' - `effect_source` ∈ {"zone", "metro", "none"} — which pin the estimate is from.
#' - `effect_reason` — only for "none": `"duplicate_id"` when the id is the
#'   `840`-prefixed form of a 9-digit US AQS id that is also in the roster (the
#'   same site twice; `duplicate_of` names the 9-digit id); `"no_policy"` (no pricing scheme) or `"not_modelled"` (a scheme the
#'   estimand does not treat, e.g. toll facilities) for a
#'   comparison city (`treated = FALSE`: no pin is read); otherwise
#'   `"no_effect_cell"` (no per-monitor-day cell survives the estimand cuts in
#'   any pin asked).
#' - `first_obs_date` / `last_obs_date` (Date) — the monitor's first and last
#'   day with a non-missing `outcome` value in `public.model_panel_daily`, for
#'   EVERY row (not only "none"). Filled only when `obs_range` is supplied (the
#'   batch publisher reads it once via `fetch_monitor_obs_range()`); NA
#'   otherwise, which is what the live handler serves — it never runs the
#'   panel scan per request.
#' - `duplicate_of` (chr, NA unless a duplicate). Duplicate rows are flagged,
#'   never dropped: the UI decides.
#'
#' Zone-scope values are unchanged by construction: zone rows are taken first
#' and the metro pin only fills monitors the zone pin left empty.
#'
#' @param roster Tibble with at least `monitor_id`.
#' @param scope "auto" (zone then metro), "zone", or "metro".
#' @param obs_range Optional output of `fetch_monitor_obs_range()` (columns
#'   `metro_id`, `fullaqsid`, `first_<outcome>`, `last_<outcome>`). Joined by
#'   (`metro_id`, `monitor_id == fullaqsid`). NULL = both date columns NA. A
#'   duplicate row with no dates of its own copies its twin's.
#' @param treated TRUE = read the pins; FALSE = comparison city, read NO pin,
#'   every effect column NA and `effect_reason = "no_policy"`; NULL (default)
#'   = decide via `.cpportal_metro_may_have_effects()` (no pin, unknown = TRUE).
#' @return `roster` with `att`, `se`, `ci_lo`, `ci_hi`, `n_days`, `basis`,
#'   `estimand`, `effect_source`, `effect_reason`, `first_obs_date`,
#'   `last_obs_date`, `duplicate_of`.
cpportal_monitor_effects_with_source <- function(roster,
                                                 metro_id,
                                                 pollutant = "PM2.5",
                                                 spec_id = "all_priority",
                                                 outcome = "aq_daily_mean",
                                                 scope = "auto",
                                                 obs_range = NULL,
                                                 treated = NULL) {
  scope <- tolower(trimws(as.character(scope %||% "auto")))
  scopes <- switch(scope, auto = c("zone", "metro"), zone = "zone",
                   metro = "metro", stop("scope must be auto, zone or metro"))
  # A comparison city (no congestion-pricing policy) has no treated cell in any
  # pin, so loading two full FECT pins only to learn that is pure cost (27.8 s
  # cold for Taipei). `treated = FALSE` skips every pin; NULL asks the
  # in-process metros table (no pin) and loads pins unless it says "no policy".
  if (is.null(treated)) treated <- .cpportal_metro_may_have_effects(metro_id)
  if (!isTRUE(treated)) scopes <- character(0L)

  eff_cols <- c("att", "se", "ci_lo", "ci_hi", "n_days", "basis", "estimand")
  out <- dplyr::select(roster, -dplyr::any_of(c(eff_cols, "effect_source",
                                                "effect_reason", "first_obs_date",
                                                "last_obs_date", "duplicate_of")))
  out$monitor_id <- as.character(out$monitor_id)

  # Zone first; each later scope only fills monitors still without an effect.
  got <- NULL
  for (sc in scopes) {
    e <- tryCatch(
      cpportal_monitor_window_effects(metro_id = metro_id, pollutant = pollutant,
                                      spec_id = spec_id, outcome = outcome,
                                      scope = sc),
      error = function(err) {
        log_warn("api/monitors", paste0("include_effects ", sc, ": ",
                                        conditionMessage(err)))
        NULL
      }
    )
    if (!is.data.frame(e) || nrow(e) == 0L) next
    e <- dplyr::distinct(e, .data$monitor_id, .keep_all = TRUE)
    e$effect_source <- sc
    if (!is.null(got)) e <- e[!e$monitor_id %in% got$monitor_id, , drop = FALSE]
    got <- dplyr::bind_rows(got, e)
  }
  if (is.null(got)) {
    got <- tibble::tibble(monitor_id = character(), att = numeric(),
                          se = numeric(), ci_lo = numeric(), ci_hi = numeric(),
                          n_days = integer(), basis = character(),
                          estimand = character(), effect_source = character())
  }
  out <- dplyr::left_join(out, got[, c("monitor_id", eff_cols, "effect_source")],
                          by = "monitor_id")

  # 840 + 9-digit US AQS id whose 9-digit form is also in the roster = same site.
  ids <- out$monitor_id
  stripped <- ifelse(grepl("^840[0-9]{9}$", ids), substring(ids, 4L), NA_character_)
  out$duplicate_of <- ifelse(!is.na(stripped) & stripped %in% ids, stripped,
                             NA_character_)

  none <- is.na(out$effect_source)
  out$effect_source[none] <- "none"
  # Untreated city: "not_modelled" when it HAS a pricing scheme the estimand
  # does not treat (e.g. Houston / Minneapolis toll facilities, system_type
  # "facility" — the treated set is cordon,ULEZ); "no_policy" when it has none.
  untreated_reason <- if (isTRUE(.cpportal_metro_has_known_policy(metro_id))) {
    "not_modelled"
  } else {
    "no_policy"
  }
  out$effect_reason <- ifelse(
    none,
    ifelse(!is.na(out$duplicate_of), "duplicate_id",
           if (isTRUE(treated)) "no_effect_cell" else untreated_reason),
    NA_character_
  )
  out$first_obs_date <- rep(as.Date(NA), nrow(out))
  out$last_obs_date <- rep(as.Date(NA), nrow(out))
  first_col <- paste0("first_", outcome)
  last_col <- paste0("last_", outcome)
  if (is.data.frame(obs_range) && nrow(obs_range) > 0L &&
      all(c("metro_id", "fullaqsid") %in% names(obs_range))) {
    mid <- as.integer(metro_id)
    rng <- obs_range[as.integer(obs_range$metro_id) == mid, , drop = FALSE]
    i <- match(out$monitor_id, as.character(rng$fullaqsid))
    if (first_col %in% names(rng)) out$first_obs_date <- as.Date(rng[[first_col]])[i]
    if (last_col %in% names(rng)) out$last_obs_date <- as.Date(rng[[last_col]])[i]
  }
  # An 840-prefixed duplicate with no panel dates of its own borrows its
  # 9-digit twin's: same site, and the panel stores it under one id only.
  twin <- match(out$duplicate_of, out$monitor_id)
  fill <- !is.na(twin) & is.na(out$first_obs_date) & is.na(out$last_obs_date)
  out$first_obs_date[fill] <- out$first_obs_date[twin[fill]]
  out$last_obs_date[fill] <- out$last_obs_date[twin[fill]]
  out
}

#' Can this metro carry a per-monitor effect in any pin? Answered WITHOUT a pin
#' from the in-process metros table (`fetch_metros()`, memoised after its first
#' call): a metro with no treated `congestion_pricing_periods` row has no
#' treated cell in any FECT pin. Conservative: anything unknown (no DB, mock
#' roster, metro absent, fetch error) answers TRUE so the pins are still read.
.cpportal_metro_may_have_effects <- function(metro_id) {
  mid <- suppressWarnings(as.integer(metro_id))
  if (length(mid) != 1L || is.na(mid)) return(TRUE)
  if (!isTRUE(tryCatch(cpportal_use_db(), error = function(e) FALSE))) return(TRUE)
  m <- tryCatch(fetch_metros(priority_only = FALSE), error = function(e) NULL)
  if (!is.data.frame(m) || !all(c("metro_id", "treated_date") %in% names(m))) {
    return(TRUE)
  }
  row <- m[as.integer(m$metro_id) == mid, , drop = FALSE]
  if (nrow(row) == 0L) return(TRUE)
  any(!is.na(row$treated_date))
}

#' Does this metro have a treated `congestion_pricing_periods` row of ANY
#' system_type? Strict, unlike `.cpportal_metro_may_have_effects()`: TRUE only
#' when the metros table says so; unknown (no DB, mock, fetch error) = FALSE.
#' Only labels an untreated city "not_modelled" vs "no_policy".
.cpportal_metro_has_known_policy <- function(metro_id) {
  mid <- suppressWarnings(as.integer(metro_id))
  if (length(mid) != 1L || is.na(mid)) return(FALSE)
  if (!isTRUE(tryCatch(cpportal_use_db(), error = function(e) FALSE))) return(FALSE)
  m <- tryCatch(fetch_metros(priority_only = FALSE), error = function(e) NULL)
  if (!is.data.frame(m) || !all(c("metro_id", "treated_date") %in% names(m))) {
    return(FALSE)
  }
  row <- m[as.integer(m$metro_id) == mid, , drop = FALSE]
  nrow(row) > 0L && any(!is.na(row$treated_date))
}

