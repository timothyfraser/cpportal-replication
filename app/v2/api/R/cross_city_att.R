#' ---------------------------------------------------------------------------
#' CHARGED-DAYS ("excluding inactive days") — THE UNIVERSAL POOLING ESTIMAND
#' ---------------------------------------------------------------------------
#' Tim's ruling, 2026-08-03 (DESIGN §36/§37): a day a cordon does not actually
#' charge is only SEMI-TREATED, and pooling it beside fully-charged days muddies
#' the estimand. So it is dropped at the POOLING stage, for EVERY method and
#' EVERY basis — `fect` fitted rows included, not just anchored ones. This is
#' the estimand, not an arm flag: two cities' ATTs are only comparable if both
#' answer "effect on a charged day".
#'
#' It touches NOTHING upstream: models are still FIT on all days (weekends carry
#' the dow/seasonal structure), and the gap model, c(M) and T_f/freeze all still
#' see every day.
#'
#' EITHER/OR ACROSS SCHEMES — Tim's refinement, 2026-08-09, verbatim:
#'
#'   "it's an EITHER OR policy, not an AND/BOTH policy … those monitors IN the
#'    CCZ on weekends ARE treated during the ULEZ period because they are
#'    affected by a traffic cordon."
#'
#' So the estimand is: a (monitor, day) is charged iff AT LEAST ONE scheme whose
#' zone covers the monitor has an active period covering the day AND charges on
#' that weekday. A metro can host several schemes on different schedules —
#' London's CCZ charges Mon–Fri, its ULEZ charges 7/7 — so a single weekday map
#' per metro (the pre-2026-08-09 encoding) wrongly dropped London weekends
#' throughout the ULEZ era.
#'
#' This layer sees only (metro_id, day): it cannot tell which monitor sits in
#' which zone. It therefore implements the METRO-GRAIN collapse of the rule: a
#' metro-day is dropped only if EVERY scheme of the metro in force that day is
#' uncharged (`charge_calendar_metro_uncharged()`).
#'
#' APPROXIMATION, STATED LOUDLY (verified at source 2026-08-09,
#' public.monitors × public.zones, ST_Intersects): during
#' 2019-04-08..2021-10-24 the central ULEZ zone covered 29 of the 34 monitors
#' inside the CCZ core zone. The five that fell OUTSIDE it were still Mon–Fri
#' only, and three of them carry weekend panel rows — 485 monitor-days — that
#' this metro-grain form counts as charged when they were not. From 2021-10-25
#' (inner expansion) onward the residual is EXACTLY ZERO. The train side has
#' monitor identity and applies the exact per-pair rule.
#'
#' CHARGE CALENDAR (Tim 2026-09-30). The schedule is no longer a literal in this
#' file. ONE resolver, `R/charge_calendar.R`, reads ONE data file,
#' `data/charge_calendar.csv` (+ `charge_calendar.bib`), and the train flip
#' (`job/model/fect/train/functions.R`), this filter and BREATHE all call it —
#' the vendored copies are regenerated by the bundles' `setup.R`, never
#' hand-edited. A missing calendar is a HARD ERROR at the first filter call,
#' never a silent "everything charged". Only `evidence = conclusive` rows make a
#' day uncharged (uncertain => charged); the weekday map in charge_calendar.R is
#' the fallback where no row speaks.
if (!exists("charge_calendar_metro_uncharged_lookup", mode = "function")) {
  local({
    for (p in c(if (exists(".api_r_dir")) file.path(.api_r_dir, "charge_calendar.R"),
                "R/charge_calendar.R", "app/v2/api/R/charge_calendar.R",
                "job/cache_publish/R/charge_calendar.R", "../R/charge_calendar.R")) {
      if (file.exists(p)) { source(p, local = FALSE); return(invisible(TRUE)) }
    }
    stop("cross_city_att.R: R/charge_calendar.R not found -- the charged-days ",
         "filter cannot run without it (refusing to treat every day as charged)")
  })
}

#' Drop inactive (non-charging) days before a pool.
#'
#' Only ever REMOVES rows, never edits them, so an unregistered metro and a
#' disabled call are both exact no-ops. Rows with an unparseable date or a
#' non-finite metro id are always kept.
#'
#' @param rows Tibble with a metro id column and a Date column.
#' @param date_col,metro_col Column names (defaults match the cross-city cache).
#' @param include_inactive DIAGNOSTIC ESCAPE HATCH. TRUE returns `rows`
#'   untouched — the pre-2026-08-03 all-days pool. Never the serving default.
#' @return `rows` with inactive-day rows removed.
#'
#' PERFORMANCE (2026-10-01; ADR-0043 addendum). The publish job calls this
#' hundreds to thousands of times per render, and it used to re-resolve the
#' calendar on every cell each time (a 62-minute render). It now answers from
#' (a) the `.charged_metro_grain` stamp the bundle loader writes once per pin
#' load (`cpportal_stamp_charged_days()`), else (b) the memoised day-grid
#' lookup `charge_calendar_metro_uncharged_lookup()`. Both are the SAME
#' resolver's answers for the same (metro_id, day), so the rows kept are
#' identical; `tests/test_charge_calendar_perf.R` is the parity gate and
#' `CPPORTAL_CHARGE_CALENDAR_FAST=0` restores the direct per-call resolver.
cpportal_charged_days_filter <- function(rows, date_col = "day",
                                         metro_col = "metro_id",
                                         include_inactive = FALSE) {
  if (isTRUE(include_inactive)) return(rows)
  if (is.null(rows) || !is.data.frame(rows) || nrow(rows) == 0L) return(rows)
  if (!all(c(date_col, metro_col) %in% names(rows))) return(rows)
  # Either/or at metro grain, via the shared charge-calendar resolver. NA-safe:
  # a row with a non-finite metro id or an unparseable date is never dropped.
  fast <- exists("charge_calendar_metro_uncharged_lookup", mode = "function") &&
    charge_calendar_fast_enabled()
  # The stamp was computed from `day` + `metro_id`, so it is trusted only for
  # those two columns, and only when complete (one non-NA logical per row).
  stamp <- if (fast && identical(date_col, "day") && identical(metro_col, "metro_id"))
    rows[[CPPORTAL_CHARGED_STAMP_COL]] else NULL
  drop <- if (is.logical(stamp) && length(stamp) == nrow(rows) && !anyNA(stamp)) {
    !stamp
  } else if (fast) {
    charge_calendar_metro_uncharged_lookup(rows[[metro_col]], rows[[date_col]])
  } else {
    charge_calendar_metro_uncharged(rows[[metro_col]], rows[[date_col]])
  }
  rows[!drop, , drop = FALSE]
}

#' Stamp the metro-grain charged flag on a pin's ATT rows, ONCE per load.
#' The column name is `CPPORTAL_CHARGED_STAMP_COL` (R/charge_calendar.R).
#'
#' Called by the bundle loaders (`load_fect_bundle()` in R/models.R, which
#' also serves job/cache_publish/publish_ref.R, and `local_pin_read()` in
#' results/local_pin.R). Rows without a day (per_metro, per_metro_month) get
#' TRUE, which is what the filter does with an NA date (never dropped).
#' A no-op when the fast path is off, so `CPPORTAL_CHARGE_CALENDAR_FAST=0`
#' reproduces the pre-2026-10-01 bundle exactly.
#'
#' The stamp is a function of (metro_id, day) and the calendar loaded in this
#' process; a calendar re-read with different content mid-process needs a
#' bundle reload (`load_fect_bundle(refresh = TRUE)`) to restamp. A payload
#' that serialized raw pin rows wholesale would carry the extra column; the
#' att / att-by-year / trajectories bodies are byte-compared with and without
#' the fast path in tests/bench_pool.R.
cpportal_stamp_charged_days <- function(att) {
  if (!is.data.frame(att) || nrow(att) == 0L) return(att)
  if (!all(c("day", "metro_id") %in% names(att))) return(att)
  if (!exists("charge_calendar_metro_uncharged_lookup", mode = "function") ||
      !charge_calendar_fast_enabled()) return(att)
  att[[CPPORTAL_CHARGED_STAMP_COL]] <-
    !charge_calendar_metro_uncharged_lookup(att$metro_id, att$day)
  # Pin identity for the cpportal_fitted_cells() memo: unique per load in
  # this process, so a reload (refresh = TRUE, a new pin) invalidates it.
  .nl <- .cpportal_cells_memo$n_loads
  .cpportal_cells_memo$n_loads <- (if (is.null(.nl)) 0L else .nl) + 1L
  attr(att, "cpportal_att_id") <- paste0(Sys.getpid(), "-",
                                         .cpportal_cells_memo$n_loads, "-",
                                         format(Sys.time(), "%Y%m%d%H%M%OS6"))
  att
}

#' Serving pool mode — which fitted-basis aggregator the combiners run.
#'
#' "ivw_flat" (DEFAULT, Tim's 2026-08-14 estimand ruling): flat inverse-variance
#' pool over monitor-day cells, no between-monitor variance component, no D2a
#' fallback. "d2c" is the ROLLBACK to the pre-ruling behaviour (fitted D2b
#' variance split where `varc_*` are present, plus the additive s²_B/J term).
#' Set `CPPORTAL_ATT_POOL=d2c` to restore it. Anchored paths ignore this.
cpportal_att_pool_mode <- function() {
  v <- tolower(trimws(Sys.getenv("CPPORTAL_ATT_POOL", "")))
  if (v %in% c("d2c", "d2b", "legacy")) "d2c" else "ivw_flat"
}

#' Drop episode-flagged day rows before pooling (fail-open if column absent).
#'
#' Production pins may carry `episode_flag` on day-grain ATT rows (rel99_x2 +
#' +/-1d dilation; scoring/pooling exclusion only). When the column is missing
#' (older pins), rows pass through unchanged.
cpportal_episode_days_filter <- function(rows) {
  if (is.null(rows) || !is.data.frame(rows) || nrow(rows) == 0L) return(rows)
  if (!("episode_flag" %in% names(rows))) return(rows)
  rows[!(rows$episode_flag %in% TRUE), , drop = FALSE]
}

#' THE ONE POOL — `cpportal_pool_att()` (ADR-0043; formerly the body of
#' `combine_att_window_d2b()`, which is now an alias of it).
#'
#' D2b / IVW window aggregation — combine per-day (or unit-day) rows over an
#' arbitrary set of days into a single ATT + SE.
#'
#' Point estimate:
#'   - anchored: Huber M-estimate (heavy-tailed by construction)
#'   - fitted + D2b components present: plain mean (historical D2b contract)
#'   - fitted + D2b absent: inverse-variance weighted mean of day-level ATTs
#'
#' SE preference:
#'   - D2b (any basis, when `varc_*` present):
#'       sqrt(mean(varc_shared_md) + mean(varc_indep_md) / n_days)
#'   - fitted without D2b (Tim, 2026-08-12 — Table 1 / `/window`):
#'       IVW SE = sqrt(1 / sum(w)), w = 1/se_att² across day rows.
#'       Synthetic-control day-level SEs stay tight even at J = 1 (dozens of
#'       controls); hundreds of day-level effects must √n-shrink. Do **not**
#'       fall back to D2a `mean(se_att)` for fitted — that was a fallacy that
#'       left Milan/Bergen window CIs absurdly wide.
#'   - anchored without D2b: D2a `mean(se_att)` (conservative; shared anchor
#'     error must not √n-shrink). Anchored is not the production path for the
#'     fitted J = 1 cities Tim ruled on.
#'
#' Charged-days + episode exclusion run here (fail-open if columns/maps absent)
#' so `/window` and every other combiner share the universal estimand cut.
#' `include_inactive = TRUE` is the diagnostic escape hatch (never a reporting
#' option) — same contract as `cpportal_charged_days_filter`.
#'
#' ESTIMAND RULING — Tim, 2026-08-14. Verbatim:
#'
#'   "every ATT uses flat IVW over monitor-day effects (w = 1/se² per
#'    monitor-day cell, one pool, no s²_B between-monitor term, no D2a
#'    fallback, no per-monitor stage)"
#'
#' So on the FITTED basis this function now ALWAYS runs the flat inverse-
#' variance pool over whatever cell rows it is handed —
#'
#'   att = Σ(w·a) / Σw ,  se = sqrt(1 / Σw) ,  w = 1 / se_att²
#'
#' — tagged `se_source = "ivw_monitor_day_flat"`. The historical fitted D2b
#' branch (`varc_shared + varc_indep / n`) is retired to the rollback switch
#' `CPPORTAL_ATT_POOL=d2c`. Where only metro-day rows exist (fitted J = 1, or a
#' pin with no unit grain) the formula is identical math over those rows, so the
#' degradation is exact rather than approximate. ANCHORED paths are UNCHANGED:
#' the ruling covers the fitted monitor-day cells, and the M10 anchor has none.
#'
#' `rows` is a tibble of per-day / per-monitor-day rows already restricted to the
#' target metro and calendar window; `basis` is "fitted" or "anchored". Returns
#' a one-row tibble with `att`, `se_att`, `att_lo`, `att_hi`, `n_days`, `basis`,
#' plus optional diagnostic components (`se_source`, `varc_*`, `yhat0`, `pct`).
cpportal_pool_att <- function(cells, basis = c("fitted", "anchored"),
                              include_inactive = FALSE,
                              mode = cpportal_att_pool_mode()) {
  # ===========================================================================
  # THE ONE POOL (pooling unification, 2026-09-30; ADR-0043). Every ATT that
  # CP Portal serves or prints goes through this function: the paper's
  # `t1_flat_ivw_pool()` (paper_pool.R), every `/cross-city-att/*` window,
  # `/att`, `/per-metro-overall`, `/monitor-*-att-series`, `/breathe/*`, and the
  # results pipeline. `combine_att_window_d2b()` is kept as a thin alias of it.
  #
  # `cells` are per-monitor-day (or, for a J = 1 city, per-metro-day) rows. The
  # universal estimand cuts run HERE, so a caller cannot forget them:
  #   * `cpportal_charged_days_filter()` — the charge-calendar resolver;
  #   * `cpportal_episode_days_filter()` — `episode_flag` from episode_lib.R.
  # Both only REMOVE rows, so re-running them on already-filtered cells is an
  # exact no-op (idempotent).
  #
  # FITTED (Tim 2026-08-14): flat inverse-variance mean over the cells,
  #   w = 1/se_att^2,  att = sum(w a)/sum(w),  se = sqrt(1/sum(w)),
  #   yhat0 = sum(w y)/sum(w) over the same cells (finite y only),
  #   n_days = number of usable cells, n_monitors = distinct monitor ids.
  # ANCHORED (M10, unchanged): Huber location; D2b SE sqrt(mean varc_shared +
  #   mean varc_indep / n) with D2a mean(se_att) fallback; Huber yhat0.
  # `mode = "d2c"` is the documented rollback (CPPORTAL_ATT_POOL=d2c) for fitted
  # rows carrying varc_*; the paper passes mode = "ivw_flat" explicitly.
  # ===========================================================================
  basis <- match.arg(basis)
  rows <- cells
  # Universal estimand cuts (fail-open on missing columns): inactive days + episode_flag==TRUE.
  rows <- cpportal_charged_days_filter(rows, include_inactive = include_inactive)
  rows <- cpportal_episode_days_filter(rows)
  if (is.null(rows) || nrow(rows) == 0L) return(.cpportal_pool_empty(basis))
  .cpportal_pool_core(rows, basis, mode)
}

#' The one pool's fields when no cell survives the cuts.
.cpportal_pool_empty_fields <- function(basis) {
  list(att = NA_real_, se_att = NA_real_,
       att_lo = NA_real_, att_hi = NA_real_,
       n_days = 0L, basis = basis,
       yhat0 = NA_real_, pct = NA_real_,
       se_source = NA_character_,
       varc_shared = NA_real_, varc_indep = NA_real_,
       n_monitors = 0L, pool = NA_character_)
}
.cpportal_pool_empty <- function(basis) {
  tibble::new_tibble(.cpportal_pool_empty_fields(basis), nrow = 1L)
}

#' The one pool's row over cells that already passed the estimand cuts.
#'
#' PERF (2026-10-01): built with `tibble::new_tibble()`, not `tibble::tibble()`
#' -- the result is `identical()` (same columns, types, class, row.names;
#' checked in tests/test_charge_calendar_perf.R) and costs ~0.15 ms instead of
#' ~13 ms, which was more than half of every pool call.
.cpportal_pool_core <- function(rows, basis, mode) {
  tibble::new_tibble(.cpportal_pool_fields(rows, basis, mode), nrow = 1L)
}

#' The one pool's ARITHMETIC, as a named list of length-1 fields. Split out of
#' `cpportal_pool_att()` (perf, 2026-10-01) so the grouped
#' `cpportal_pool_att_by()` runs the very same lines per group; the body below
#' is the pre-split body verbatim except `numc()` and the final constructor.
.cpportal_pool_fields <- function(rows, basis, mode) {
  # numc(): a plain double column passes through untouched. It used to be
  # `as.numeric(as.character(x))` for every column -- a string round trip that
  # was ~1 s of one London /att call and that ROUNDS a double to 15
  # significant digits on the way. Anything else (integer, character, factor,
  # integer64) still takes the old coercion, so only plain doubles change, and
  # only below the 15th significant digit (measured in tests/bench_pool.R).
  numc <- function(x) if (is.double(x) && !is.object(x)) x else
    suppressWarnings(as.numeric(as.character(x)))
  has  <- function(col) col %in% names(rows)

  att_vec <- numc(rows$att)
  se_vec  <- if (has("se_att")) numc(rows$se_att) else rep(NA_real_, length(att_vec))
  yhat0_vec <- if (has("yhat0")) numc(rows$yhat0) else rep(NA_real_, length(att_vec))
  n <- length(att_vec)

  # D2b components — preferred when the pin carries them (anchored M10 path).
  vs <- if (has("varc_shared_md")) mean(numc(rows$varc_shared_md), na.rm = TRUE) else NA_real_
  vi <- if (has("varc_indep_md"))  mean(numc(rows$varc_indep_md),  na.rm = TRUE) else NA_real_
  se_d2b <- if (is.finite(vs) && is.finite(vi)) sqrt(vs + vi / n) else NA_real_

  se_d2a <- if (any(is.finite(se_vec))) mean(se_vec, na.rm = TRUE) else NA_real_
  se_source <- NA_character_
  used <- rep(TRUE, length(att_vec))
  pool <- NA_character_

  if (identical(basis, "anchored")) {
    att_point <- .huber_location(att_vec)
    se <- dplyr::coalesce(se_d2b, se_d2a)
    se_source <- dplyr::case_when(
      is.finite(se_d2b) ~ "d2b_shared_plus_indep_over_n",
      is.finite(se_d2a) ~ "d2a_mean_se_att",
      TRUE              ~ NA_character_
    )
    yhat0_point <- if (any(is.finite(yhat0_vec))) .huber_location(yhat0_vec) else NA_real_
    pool <- "anchored_huber_d2b"
  } else if (is.finite(se_d2b) && identical(mode, "d2c")) {
    # ROLLBACK ONLY (CPPORTAL_ATT_POOL=d2c): fitted rows that carry varc_* keep
    # the pre-2026-08-14 D2b contract.
    att_point <- mean(att_vec, na.rm = TRUE)
    se <- se_d2b
    se_source <- "d2b_shared_plus_indep_over_n"
    yhat0_point <- if (any(is.finite(yhat0_vec))) mean(yhat0_vec, na.rm = TRUE) else NA_real_
    pool <- "d2c_rollback"
  } else {
    # FITTED PRODUCTION PATH: flat IVW over the cells handed in. Same usable-cell
    # rule as `inverse_variance_mean()` / the paper (finite att, finite se > 0).
    used <- is.finite(att_vec) & is.finite(se_vec) & se_vec > 0
    if (any(used)) {
      a <- att_vec[used]; s <- se_vec[used]; y <- yhat0_vec[used]
      w <- 1 / (s * s)
      sw <- sum(w)
      att_point <- sum(w * a) / sw
      se <- sqrt(1 / sw)
      n <- as.integer(sum(used))
      # The counterfactual is pooled under the SAME weights (the paper's rule),
      # so pct = 100 * sum(w a) / sum(w y) over the very same cells.
      yhat0_point <- if (any(is.finite(y))) sum(w[is.finite(y)] * y[is.finite(y)]) /
                                            sum(w[is.finite(y)]) else NA_real_
      se_source <- if (identical(mode, "d2c")) "ivw_day_pool" else "ivw_monitor_day_flat"
    } else {
      att_point <- NA_real_; se <- NA_real_; yhat0_point <- NA_real_
    }
    pool <- "monitor_ivw"
  }

  pct_change <- if (is.finite(yhat0_point) && abs(yhat0_point) > 1e-9 &&
                    is.finite(att_point)) {
    att_point / yhat0_point * 100
  } else NA_real_

  idc <- .cpportal_unit_id_col(rows)
  n_mon <- if (!is.na(idc)) {
    ids <- as.character(rows[[idc]])[used]
    ids <- ids[nzchar(ids)]   # same rule the paper's J disclosure always used
    if (length(ids)) length(unique(ids)) else 1L
  } else 1L

  list(
    att      = att_point,
    se_att   = se,
    att_lo   = att_point - 1.96 * se,
    att_hi   = att_point + 1.96 * se,
    n_days   = as.integer(n),
    basis    = basis,
    # Native counterfactual level over the same cells, and ATT as a % of it.
    yhat0    = yhat0_point,
    pct      = pct_change,
    # Diagnostics — surface which SE branch fired so consumers can see it.
    se_source = se_source,
    varc_shared = vs,
    varc_indep  = vi,
    # Disclosure, never a weight: distinct monitors among the usable cells.
    n_monitors = as.integer(n_mon),
    pool = pool
  )
}

#' First day of each Date's calendar month — the same value as
#' `as.Date(format(as.Date(d), "%Y-%m-01"))` without format() + strptime(),
#' which cost ~0.4 s per London /att call (perf, 2026-10-01). Computed once
#' per cell table; checked against the format() form in
#' tests/test_charge_calendar_perf.R.
cpportal_month_start <- function(d) {
  x <- floor(unclass(as.Date(d)))
  x[!is.finite(x)] <- NA
  .Date(x - (as.POSIXlt(.Date(x))$mday - 1L))
}

#' Back-compatible alias of `cpportal_pool_att()`. Every historical caller of
#' the "D2b combiner" now runs THE one pool; there is no second body.
combine_att_window_d2b <- function(rows, basis = c("fitted", "anchored"),
                                   include_inactive = FALSE) {
  cpportal_pool_att(rows, basis = match.arg(basis),
                    include_inactive = include_inactive)
}

#' THE ONE POOL, GROUPED — `cpportal_pool_att()` for every group of `cells` in
#' ONE pass (perf, 2026-10-01; ADR-0043 addendum).
#'
#' Row k of the result is `cpportal_pool_att(cells[group k, ], basis, ...)`,
#' by construction: the estimand cuts are ROW-WISE (each row kept or dropped
#' on its own metro_id / day / episode_flag), so cutting once and splitting is
#' the same as splitting and cutting each group, and each group then runs the
#' same `.cpportal_pool_core()`. What it saves is the per-group overhead the
#' monthly / yearly callers paid through `group_by() |> group_modify()`.
#'
#' @param by A column name of `cells`, or a vector parallel to its rows.
#' @return One row per group PRESENT IN `cells` (before the cuts — a group the
#'   cuts empty gets the empty-pool row, exactly as `group_modify()` gave it),
#'   in ascending key order (NA last): the key column first (named `by` when
#'   `by` is a column name, else `group`), then `cpportal_pool_att()`'s columns.
cpportal_pool_att_by <- function(cells, by, basis = c("fitted", "anchored"),
                                 include_inactive = FALSE,
                                 mode = cpportal_att_pool_mode()) {
  basis <- match.arg(basis)
  key_name <- if (is.character(by) && length(by) == 1L && by %in% names(cells)) by else "group"
  key <- if (identical(key_name, "group")) by else cells[[by]]
  if (length(key) != nrow(cells)) stop("cpportal_pool_att_by(): `by` must be parallel to `cells`")
  ukeys <- sort(unique(key), na.last = TRUE)
  rows <- cells
  rows[[".cpportal_pool_by"]] <- match(key, ukeys)
  rows <- cpportal_charged_days_filter(rows, include_inactive = include_inactive)
  rows <- cpportal_episode_days_filter(rows)
  g <- rows[[".cpportal_pool_by"]]
  rows[[".cpportal_pool_by"]] <- NULL
  idx <- split(seq_len(nrow(rows)), factor(g, levels = seq_along(ukeys)))
  res <- lapply(idx, function(i) {
    if (!length(i)) .cpportal_pool_empty_fields(basis)
    else .cpportal_pool_fields(rows[i, , drop = FALSE], basis, mode)
  })
  proto <- .cpportal_pool_empty_fields(basis)
  cols <- lapply(stats::setNames(names(proto), names(proto)), function(nm) {
    if (!length(res)) return(proto[[nm]][0])
    unlist(lapply(res, `[[`, nm), use.names = FALSE)
  })
  tibble::new_tibble(c(stats::setNames(list(ukeys), key_name), cols),
                     nrow = length(ukeys))
}

